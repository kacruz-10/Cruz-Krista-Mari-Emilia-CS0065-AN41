import string

with open("happy_words.txt", "r") as f:
    happy_words = [line.strip().lower() for line in f if line.strip()]

with open("sad_words.txt", "r") as f:
    sad_words = [line.strip().lower() for line in f if line.strip()]


def clean_words(sentence):
    sentence = sentence.lower().translate(str.maketrans("", "", string.punctuation))
    return sentence.split()


def number_happy(sentence):
    words = clean_words(sentence)
    count = 0
    for word in words:
        if word in happy_words:
            count += 1
    return count


def number_sad(sentence):
    words = clean_words(sentence)
    count = 0
    for word in words:
        if word in sad_words:
            count += 1
    return count


sentence = input("Enter a sentence: ")

happy = number_happy(sentence)
sad = number_sad(sentence)

print("\n")
print("Happy words:", happy)
print("Sad words:", sad)
print("\n")

if happy > sad:
    print("The tone of the sentence is happy.")
elif sad > happy:
    print("The tone of the sentence is sad.")
else:
    print("The tone of the sentence is neutral.")