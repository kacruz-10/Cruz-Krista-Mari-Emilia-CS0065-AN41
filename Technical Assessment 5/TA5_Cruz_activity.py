from textblob import TextBlob

pos = 0
neu = 0
neg = 0

for i in range(1, 11):
    sentence = input(f"Enter a sentence ({i}/10): ")
    s = TextBlob(sentence)
    p = s.sentiment.polarity

    if p < 0:
        print("Negative")
        neg += 1
    elif p == 0:
        print("Neutral")
        neu += 1
    elif p > 0 and p <= 1:
        print("Positive")
        pos += 1

print("\n" + "=" * 35)
print("SENTIMENT ANALYSIS SUMMARY")
print("=" * 35)
print("Positive:", pos)
print("Neutral:", neu)
print("Negative:", neg)